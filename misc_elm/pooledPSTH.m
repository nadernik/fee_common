dir = 'C:/users/emackev/Documents/MATLAB/Figures/HVC_Tutoring/'; 

N = numel(HVCunits);

for ni = 1:N; 
    % check datastart and datastop
    load([dir HVCunits{ni}]);
    display([HVCunits{ni}, ' data starts at ', num2str(trigInfo.dataStart{1})])
    event_idx = strmatch('[Events] Spikes', trigInfo.eventNames);
    event_idx = event_idx(1);
    neuron_onset{ni} = [];
    neuron_offset{ni} = [];
    for ti = 1:numel(trigInfo.absTime)
        onset_spike_times{ni}{ti} = trigInfo.eventOnsets{event_idx}{ti};
        offset_spike_times{ni}{ti} = trigInfo.eventOnsets{event_idx}{ti}-...
            trigInfo.currTrigOffset(ti);
        neuron_onset{ni} = [neuron_onset{ni}; onset_spike_times{ni}{ti}];
        neuron_offset{ni} = [neuron_offset{ni}; offset_spike_times{ni}{ti}];
    end
    psth_onset(ni,:) = hist(neuron_onset{ni}, -.5:.02:1)/.02;
    psth_offset(ni,:) = hist(neuron_offset{ni}, -1.25:.02:1)/.02;
    clear trigInfo
end
figure; 
subplot(2,1,1); 
errorpatch(-.5:.02:1, mean(psth_onset), std(psth_onset))
xlabel('time relative to bout onset (s)'); xlim([-.5 .5])
ylabel('spike rate (Hz)')
subplot(2,1,2); 
errorpatch(-1.25:.02:1, mean(psth_offset), std(psth_offset))
xlabel('time relative to bout offset (s)'); xlim([-.5 .5])
ylabel('spike rate (Hz)')
